// Command tzplaces makes internal/tzplace/zones.go from the IANA tz
// database (public domain, https://www.iana.org/time-zones): every zone in
// zone.tab and zone1970.tab with the coordinates of its city, and the old
// names from backward pointing at them.
//
//	go run ./tools/tzplaces -dir <tzdata folder> -version 2026a > internal/tzplace/zones.go
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	dir := flag.String("dir", ".", "folder holding zone.tab, zone1970.tab and backward")
	ver := flag.String("version", "", "tzdata version, written into the file")
	flag.Parse()
	zones := map[string][2]float64{}
	for _, f := range []string{"zone.tab", "zone1970.tab"} {
		each(filepath.Join(*dir, f), func(cols []string) {
			if len(cols) < 3 {
				return
			}
			lat, lon, ok := coords(cols[1])
			if !ok {
				fail(fmt.Errorf("%s: bad coordinates %q", f, cols[1]))
			}
			zones[cols[2]] = [2]float64{lat, lon}
		})
	}
	links := map[string]string{}
	each(filepath.Join(*dir, "backward"), func(cols []string) {
		if len(cols) >= 3 && cols[0] == "Link" {
			links[cols[2]] = cols[1]
		}
	})
	names := make([]string, 0, len(zones))
	for z := range zones {
		names = append(names, z)
	}
	sort.Strings(names)
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/tzplaces from IANA tzdata %s (public domain). DO NOT EDIT.\n\npackage tzplace\n\n", *ver)
	fmt.Fprintf(&b, "// TZVersion is the tzdata release these come from.\nconst TZVersion = %q\n\n", *ver)
	b.WriteString("var zones = map[string][2]float64{\n")
	for _, z := range names {
		c := zones[z]
		fmt.Fprintf(&b, "\t%q: {%s, %s},\n", z, f4(c[0]), f4(c[1]))
	}
	b.WriteString("}\n\n// links are old zone names and the zone they now are.\nvar links = map[string]string{\n")
	lnames := make([]string, 0, len(links))
	for l := range links {
		lnames = append(lnames, l)
	}
	sort.Strings(lnames)
	for _, l := range lnames {
		fmt.Fprintf(&b, "\t%q: %q,\n", l, links[l])
	}
	b.WriteString("}\n")
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		fail(err)
	}
	os.Stdout.Write(out)
}

func each(path string, f func([]string)) {
	fh, err := os.Open(path)
	if err != nil {
		fail(err)
	}
	defer fh.Close()
	sc := bufio.NewScanner(fh)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		if cols := strings.Fields(line); len(cols) > 0 {
			f(cols)
		}
	}
}

// coords reads ISO 6709 like +0310+10142 or -0430+01518 or +404251-0740023.
func coords(s string) (lat, lon float64, ok bool) {
	i := strings.IndexAny(s[1:], "+-")
	if i < 0 {
		return 0, 0, false
	}
	a, b := s[:i+1], s[i+1:]
	lat, ok1 := part(a, 2)
	lon, ok2 := part(b, 3)
	return lat, lon, ok1 && ok2
}

func part(s string, degDigits int) (float64, bool) {
	sign := 1.0
	if s[0] == '-' {
		sign = -1
	}
	d := s[1:]
	if len(d) != degDigits+2 && len(d) != degDigits+4 {
		return 0, false
	}
	deg, e1 := strconv.Atoi(d[:degDigits])
	min, e2 := strconv.Atoi(d[degDigits : degDigits+2])
	sec := 0
	var e3 error
	if len(d) == degDigits+4 {
		sec, e3 = strconv.Atoi(d[degDigits+2:])
	}
	if e1 != nil || e2 != nil || e3 != nil {
		return 0, false
	}
	return sign * (float64(deg) + float64(min)/60 + float64(sec)/3600), true
}

func f4(v float64) string { return strconv.FormatFloat(math.Round(v*1e4)/1e4, 'f', -1, 64) }

func fail(err error) {
	fmt.Fprintln(os.Stderr, "tzplaces:", err)
	os.Exit(1)
}
