func TestChanServLog(t *testing.T) {
	s := testServer(t, nil)
	bee := founded(t, s, "Bee")
	ember := registered(t, s, "ember")
	x := login(t, s, "x")
	joinAll("#bchat", ember, x)
	bee.send("CS AOP #bchat ADD ember")
	x.expect("+o ember")

	bee.send("CS LOG #bchat")
	bee.expect(csLine("Bee", "#bchat logs nothing. Add one: /cs log #bchat <command> NOTICE"))
	bee.send("CS LOG #bchat KICK NOTICE @")
	bee.expect(csLine("Bee", "#bchat now tells @ and up whenever someone uses KICK."))
	ember.send("CS KICK #bchat x bye")
	x.expect(csSrc + "KICK #bchat x :(ember) bye")
	bee.expect(csSrc + "NOTICE @#bchat :ember used KICK x bye")
	ember.expect(csSrc + "NOTICE @#bchat :ember used KICK x bye")
	x.quiet("used KICK")
	ember.send("CS KICK #bchat nobody") // failed commands aren't logged
	ember.expect(csLine("ember", "nobody isn't in #bchat."))
	bee.quiet("used KICK nobody")
	bee.send("CS LOG #bchat")
	bee.expect(csLine("Bee", "Log settings of #bchat:"))
	bee.expect(csLine("Bee", "  KICK       NOTICE   @ and up"))

	bee.send("CS LOG #bchat chanserv/topic MEMO")
	bee.expect(csLine("Bee", "#bchat now leaves a channel memo whenever someone uses TOPIC."))
	ember.send("CS TOPIC #bchat hello there")
	bee.expect(csSrc + "TOPIC #bchat :hello there")
	bee.send("MS READ #bchat 1")
	bee.expect(msLine("Bee", "Memo 1 on #bchat from ChanServ · "))
	bee.expect(msLine("Bee", "  ember used TOPIC hello there"))

	bee.send("CS LOG #bchat KICK NONE")
	bee.expect(csLine("Bee", "#bchat no longer logs KICK."))
	bee.send("CS LOG #bchat FOO NOTICE")
	bee.expect(csLine("Bee", "ChanServ has no command FOO."))
	bee.send("CS LOG #bchat KICK NOTICE %") // no halfops on an @+ server
	bee.expect(csLine("Bee", "The status is one prefix this server uses, like @ (not for MEMO)."))
	ember.send("CS LOG #bchat KICK NOTICE")
	ember.expect(csLine("ember", "You need to be the founder on #bchat for that."))
}

func TestChanServSuspend(t *testing.T) {
	s, _, _ := fileServer(t, "")
	b := boss(t, s)
	bee := founded(t, s, "Bee")
	x := login(t, s, "x")
	joinAll("#bchat", x)

	bee.send("CS SUSPEND #bchat")
	bee.expect(csLine("Bee", "SUSPEND is for IRC operators with flag s."))
	b.send("CS SUSPEND #bchat +2h spam wave")
	bee.expect(csSrc + "KICK #bchat Bee :This channel is suspended: spam wave")
	x.expect(csSrc + "KICK #bchat x :This channel is suspended: spam wave")
	b.expect("Boss used ChanServ: SUSPEND #bchat for 2 hours: spam wave")
	b.expect(csLine("Boss", "#bchat is suspended for 2 hours (2 people kicked)."))

	bee.send("JOIN #bchat")
	bee.expect(csSrc + "KICK #bchat Bee :This channel is suspended: spam wave")
	bee.send("CS OP #bchat")
	bee.expect(csLine("Bee", "#bchat is suspended: spam wave"))
	bee.send("CS INFO #bchat")
	bee.expect(csLine("Bee", "  Suspended     by Boss, "))
	b.send("CS SUSPEND #bchat again")
	b.expect(csLine("Boss", "#bchat is suspended already (by Boss). UNSUSPEND it first to change that."))
	b.send("CS LIST #b*")
	b.expect("#bchat               [suspended] Be kind, stay curious")

	b.send("CS UNSUSPEND #bchat")
	b.expect("Boss used ChanServ: UNSUSPEND #bchat")
	b.expect(csLine("Boss", "#bchat can be used again."))
	bee.send("JOIN #bchat")
	bee.expect(" 366 Bee #bchat ")
	bee.quiet("suspended")

	b.send("CS SET NOEXPIRE #bchat ON")
	b.expect(csLine("Boss", "No expire is now on for #bchat."))
	b.expect("Boss used ChanServ: SET NOEXPIRE #bchat ON")
	b.send("CS HELP")
	b.expect(csLine("Boss", "Commands for IRC operators"))
	b.expect(csLine("Boss", "  SUSPEND, UNSUSPEND"))
}
