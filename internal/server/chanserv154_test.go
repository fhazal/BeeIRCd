func TestAccessLevelsAndStatus(t *testing.T) {
	s := testServer(t, nil)
	bee := founded(t, s, "Bee")
	ember := registered(t, s, "ember")
	kes := registered(t, s, "kes")
	x := login(t, s, "x")
	joinAll("#bchat", ember, kes, x)

	bee.send("CS ACCESS #bchat ADD ember 7 writes the docs")
	bee.expect(csLine("Bee", "ember added to the access list of #bchat at level 7."))
	kes.expect(csSrc + "MODE #bchat +o ember") // 7 is AUTOOP (5) and up
	bee.send("CS ACCESS #bchat ADD kes VOP")
	bee.expect(csLine("Bee", "kes added to the access list of #bchat at level VOP."))
	kes.expect(csSrc + "MODE #bchat +v kes")
	bee.send("CS ACCESS #bchat ADD kes 10001")
	bee.expect(csLine("Bee", "10001 isn't a level. Give a number from 1 to 10000, or VOP, AOP, SOP and so on."))
	ember.send("CS ACCESS #bchat ADD kes 5") // 7 is below ACCESS_CHANGE (10)
	ember.expect(csLine("ember", "You need to be SOP or higher on #bchat for that."))
	bee.send("CS ACCESS #bchat ADD ember SOP")
	bee.expect(csLine("Bee", "ember moved from level 7 to SOP on #bchat."))
	ember.send("CS ACCESS #bchat ADD kes 10")
	ember.expect(csLine("ember", "You can only give levels below your own (SOP) on #bchat."))
	ember.send("CS ACCESS #bchat ADD kes 9")
	ember.expect(csLine("ember", "kes moved from level VOP to 9 on #bchat."))
	kes.expect(csSrc + "MODE #bchat +o kes")
	ember.send("CS ACCESS #bchat ADD Bee 5")
	ember.expect(csLine("ember", "Bee is the founder of #bchat."))

	kes.send("CS ACCESS #bchat VIEW")
	kes.expect(csLine("kes", "Access list of #bchat"))
	kes.expect(csLine("kes", "  #   Level   Nick   Gets"))
	kes.expect(csLine("kes", "  –   Founder Bee    @"))
	l := kes.expect(csLine("kes", "  1   SOP     ember  @"))
	if !strings.Contains(l, "added by Bee, ") {
		t.Errorf("VIEW line without who added it: %q", l)
	}
	kes.expect(csLine("kes", "  2   9       kes    @"))
	kes.expect(csLine("kes", "3 entries."))
	kes.send("CS ACCESS #bchat CLEAR")
	kes.expect(csLine("kes", "Only the founder of #bchat can do that."))
	x.send("CS ACCESS #bchat LIST")
	x.expect(csLine("x", "Identify first: /ns identify <password>"))

	// STATUS and WHY.
	ember.send("CS STATUS #bchat")
	ember.expect(csLine("ember", "ember (account ember) is on the access list of #bchat at level SOP."))
	ember.expect(csLine("ember", "  Privileges: ACCESS_CHANGE, ACCESS_LIST, AKICK, AUTOHALFOP,"))
	ember.send("CS WHY #bchat Bee")
	ember.expect(csLine("ember", "Bee is the founder of #bchat (account Bee)."))
	ember.send("CS STATUS #bchat x")
	ember.expect(csLine("ember", "x isn't identified, so they have no access on #bchat."))
	x.send("CS STATUS #bchat")
	x.expect(csLine("x", "You aren't identified, so you have no access on #bchat."))

	// LEVELS: everyone voiced, a privilege switched off, founder-only, reset.
	bee.send("CS LEVELS #bchat LIST")
	bee.expect(csLine("Bee", "Levels of #bchat (* = changed from the default):"))
	bee.expect("  AUTOVOICE ")
	bee.send("CS LEVELS #bchat SET AUTOVOICE 0")
	bee.expect(csLine("Bee", "AUTOVOICE on #bchat now needs level 0."))
	x.expect(csSrc + "MODE #bchat +v x")
	y := login(t, s, "y")
	joinAll("#bchat", y)
	y.expect(csSrc + "MODE #bchat +v y")
	bee.send("CS LEVELS #bchat LIST")
	l = bee.expect("  AUTOVOICE ")
	if !strings.Contains(l, "0*  voice (+) on join") {
		t.Errorf("changed level not marked: %q", l)
	}
	bee.send("CS LEVELS #bchat DISABLE KICK")
	bee.expect(csLine("Bee", "KICK is now switched off on #bchat."))
	bee.send("CS KICK #bchat y")
	bee.expect(csLine("Bee", "KICK is switched off on #bchat (see /cs levels #bchat list)."))
	bee.send("CS LEVELS #bchat SET KICK FOUNDER")
	bee.expect(csLine("Bee", "KICK on #bchat is now for the founder only."))
	ember.send("CS KICK #bchat y")
	ember.expect(csLine("ember", "Only the founder of #bchat can do that."))
	ember.send("CS LEVELS #bchat SET KICK 1")
	ember.expect(csLine("ember", "Only the founder of #bchat can do that."))
	bee.send("CS LEVELS #bchat SET NOPE 1")
	bee.expect(csLine("Bee", "NOPE isn't a privilege. See /cs levels #bchat list."))
	// QA 14 Nov 2026: no privilege name gives the syntax, not " isn't a privilege".
	bee.send("CS LEVELS #bchat SET")
	bee.expect(csLine("Bee", "Syntax: LEVELS #bchat SET <privilege> {<0-10000> | FOUNDER}"))
	bee.send("CS LEVELS #bchat DISABLE")
	bee.expect(csLine("Bee", "Syntax: LEVELS #bchat DISABLE <privilege>"))
	bee.send("CS LEVELS #bchat RESET")
	bee.expect(csLine("Bee", "Every level of #bchat is back to its default."))
	ember.send("CS KICK #bchat y")
	y.expect(csSrc + "KICK #bchat y :(ember) Requested")

	// You may always take yourself off.
	kes.send("CS ACCESS #bchat DEL kes")
	kes.expect(csLine("kes", "kes removed from the access list of #bchat."))
}

