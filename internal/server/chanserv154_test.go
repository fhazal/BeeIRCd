func TestChannelMemoBox(t *testing.T) {
	s := testServer(t, nil)
	bee := founded(t, s, "Bee")
	ember := registered(t, s, "ember")
	kes := registered(t, s, "kes")
	joinAll("#bchat", ember)
	bee.send("CS SOP #bchat ADD ember")
	bee.expect("ember added to the SOP list")

	kes.send("MS SEND #bchat Can I get voice?")
	kes.expect(msLine("kes", "Memo sent to #bchat."))
	bee.expect(msLine("Bee", "There is a new memo on #bchat from kes. Read it: /ms read #bchat 1"))
	ember.expect(msLine("ember", "There is a new memo on #bchat from kes. Read it: /ms read #bchat 1"))
	ember.send("MS LIST #bchat")
	ember.expect(msLine("ember", "Memo box of #bchat:"))
	ember.expect(msLine("ember", "1 memo, 1 new. Read one: /ms read #bchat <num>"))
	ember.send("PART #bchat")
	ember.expect("PART #bchat")
	ember.send("JOIN #bchat")
	ember.expect(msLine("ember", "#bchat has 1 new memo. Read it: /ms list #bchat"))
	bee.send("MS READ #bchat NEW")
	bee.expect(msLine("Bee", "Memo 1 on #bchat from kes · "))
	bee.expect(msLine("Bee", "  Can I get voice?"))
	ember.send("PART #bchat")
	ember.send("JOIN #bchat")
	ember.expect(" 366 ember #bchat ")
	ember.quiet("new memo") // read is shared: Bee read it for the box

	// The box has its own limit and ignore list.
	bee.send("MS SET LIMIT #bchat 1")
	bee.expect(msLine("Bee", "The memo box of #bchat now keeps at most 1 memo."))
	kes.send("MS SEND #bchat again")
	kes.expect(msLine("kes", "The memo box of #bchat is full."))
	bee.send("MS IGNORE #bchat ADD kes")
	bee.expect(msLine("Bee", "Memos from kes are now dropped."))
	kes.send("MS SEND #bchat again")
	kes.expect(msLine("kes", "Memo sent to #bchat.")) // dropped without a word
	bee.send("MS IGNORE #bchat LIST")
	bee.expect(msLine("Bee", "Memos from these nicks are dropped: kes"))
	bee.send("MS IGNORE #bchat DEL kes")
	bee.expect(msLine("Bee", "Memos from kes arrive again."))
	bee.send("MS DEL #bchat ALL")
	bee.expect(msLine("Bee", "All 1 memo deleted."))
	bee.send("MS LIST #bchat")
	bee.expect(msLine("Bee", "#bchat has no memos."))
	bee.send("MS SET LIMIT #bchat 20")
	bee.expect("now keeps at most 20 memos")

	// MEMOLEVEL (ConferenceRoom) is LEVELS SET MEMO.
	kes.send("MS LIST #bchat")
	kes.expect(msLine("kes", "You need the MEMO privilege on #bchat for its memo box (SOP or higher there)."))
	bee.send("CS VOP #bchat ADD kes")
	bee.expect("kes added to the VOP list")
	bee.send("CS SET MEMOLEVEL #bchat VOP")
	bee.expect(csLine("Bee", "MEMO on #bchat now needs level VOP."))
	kes.send("MS LIST #bchat")
	kes.expect(msLine("kes", "#bchat has no memos."))

	// Identifying inside the channel tells you too.
	kes.send("MS SEND #bchat news for the box")
	kes.expect("Memo sent to #bchat.")
	ember.send("QUIT")
	ember.expect("ERROR")
	late := login(t, s, "ember")
	late.send("JOIN #bchat")
	late.expect(" 366 ember #bchat ")
	late.quiet("new memo")
	late.send("NS IDENTIFY " + pw)
	late.expect(msLine("ember", "#bchat has 1 new memo. Read it: /ms list #bchat"))
}

